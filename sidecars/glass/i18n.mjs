export function tr(lang, key, vars = null) {
  const dict = I18N[lang] || I18N['zh-CN'];
  let text = dict[key] ?? I18N['zh-CN'][key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

export function localizeSource(lang, src) {
  if (lang !== 'en') return src;
  if (src === '内置动态') return 'Built-in';
  if (src === '手动目录') return 'Custom Folder';
  if (src === '导入场景包') return 'Imported .pkg';
  return src;
}

export function localizeBuiltinTitle(lang, title) {
  if (lang !== 'en' || typeof title !== 'string') return title;
  const parts = title.split('·').map(s => s.trim());
  return parts.length === 2 && /[A-Za-z]/.test(parts[1]) ? parts[1] : title;
}

export function localizePropLabel(lang, text) {
  if (lang !== 'en') return text;
  if (text === '流动速度') return 'Flow Speed';
  if (text === '粒子密度') return 'Particle Density';
  return text;
}
