export function resolveLanguage(pref = 'auto') {
  if (pref === 'en' || pref === 'zh-CN') return pref;
  const nav = typeof navigator === 'object' ? (navigator.language || navigator.languages?.[0] || '') : '';
  return /^zh\b/i.test(nav) ? 'zh-CN' : 'en';
}

